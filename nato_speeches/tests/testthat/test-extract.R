test_that("article extraction gets title, date, clean body and PDFs", {
  a <- extract_article(fixture("speech.html"), "https://mod.example.org/news/speeches/x", src_row())
  expect_equal(a$title, "Minister's speech at the NATO summit")
  expect_equal(a$date, "2025-06-24")
  expect_equal(a$date_source, "meta")
  expect_equal(a$language, "en")
  expect_match(a$text, "five percent of our gross domestic product")
  expect_match(a$text, "An attack on one is an attack on all.")
  expect_false(grepl("tracking|Share on social|Copyright|Related:|Home / News", a$text))
  expect_equal(a$pdf_links, "https://mod.example.org/files/speech-text-full.pdf")
})

test_that("date falls back to body text, Croatian 'listopad' is October", {
  a <- extract_article(fixture("speech_nometa.html"), "https://predsjednik.example.hr/govor", src_row(language = "hr"))
  expect_equal(a$date, "2025-10-30")
  expect_equal(a$date_source, "text")
  expect_match(a$title, "^Govor predsjednika")
  expect_match(a$text, "savezništva")
})

test_that("parse_date_string handles common national formats", {
  expect_equal(parse_date_string("2025-10-03T08:00:00Z"), "2025-10-03")
  expect_equal(parse_date_string("October 3, 2025"), "2025-10-03")
  expect_equal(parse_date_string("3rd October 2025"), "2025-10-03")
  expect_equal(parse_date_string("3 octobre 2025"), "2025-10-03")
  expect_equal(parse_date_string("3. Oktober 2025"), "2025-10-03")
  expect_equal(parse_date_string("3 de octubre de 2025"), "2025-10-03")
  expect_equal(parse_date_string("3 ottobre 2025"), "2025-10-03")
  expect_equal(parse_date_string("3 października 2025"), "2025-10-03")
  expect_equal(parse_date_string("3 listopada 2025", lang = "pl"), "2025-11-03")
  expect_equal(parse_date_string("3. listopada 2025.", lang = "hr"), "2025-10-03")
  expect_equal(parse_date_string("2025. október 3."), "2025-10-03")
  expect_equal(parse_date_string("3 Ekim 2025"), "2025-10-03")
  expect_equal(parse_date_string("3 Οκτωβρίου 2025"), "2025-10-03")
  expect_equal(parse_date_string("3 октомври 2025 г."), "2025-10-03")
  expect_equal(parse_date_string("03.10.2025"), "2025-10-03")
  expect_equal(parse_date_string("3 augusti 2025"), "2025-08-03")
  expect_true(is.na(parse_date_string("no date here")))
  expect_true(is.na(parse_date_string("31.02.2025")))
})
